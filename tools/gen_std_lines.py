#!/usr/bin/env python3
"""gen_std_lines.py — generate the C twins of the std modules' embedded
line arrays.

src/y/std/rt.y and src/y/std/prelude.y carry their own source text as
`def NAME() -> [str]` literals (the shipped ycc is a standalone static
ELF and cannot read support files at run time). The 1:1 C copy needs the
same arrays compiled in; this script extracts each literal and emits
src/c/std_lines.c with one function per literal, byte-identical in
content (escapes are decoded with the Y rules and re-encoded as C).

Usage: gen_std_lines.py OUT.c SRC.y:FUNC [SRC.y:FUNC ...]
"""
import sys


def y_unescape(s: str) -> bytes:
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c != "\\":
            out += c.encode()
            i += 1
            continue
        i += 1
        if i >= len(s):
            out += b"\\"
            break
        e = s[i]
        i += 1
        if e == "n":
            out += b"\n"
        elif e == "t":
            out += b"\t"
        elif e == "r":
            out += b"\r"
        elif e == "\\":
            out += b"\\"
        elif e == '"':
            out += b'"'
        elif e == "'":
            out += b"'"
        elif e == "x" and i + 2 <= len(s):
            try:
                out.append(int(s[i : i + 2], 16))
                i += 2
            except ValueError:
                out += b"x"
        else:
            out += e.encode()  # Y drops the backslash on unknown escapes
    return bytes(out)


def c_escape(b: bytes) -> str:
    out = []
    for x in b:
        if x == 0x22:
            out.append('\\"')
        elif x == 0x5C:
            out.append("\\\\")
        elif x == 0x0A:
            out.append("\\n")
        elif x == 0x09:
            out.append("\\t")
        elif x == 0x0D:
            out.append("\\r")
        elif 0x20 <= x <= 0x7E:
            out.append(chr(x))
        else:
            out.append("\\%03o" % x)  # octal: no hex run-on surprises
    return "".join(out)


def extract(path: str, func: str):
    src = open(path).read()
    anchor = "def %s(" % func
    i = src.index(anchor)
    i = src.index("[", src.index("{", i))  # the body literal, not [str]
    depth = 0
    lits = []
    j = i
    while j < len(src):
        c = src[j]
        if c == '"':
            j += 1
            raw = []
            while src[j] != '"':
                if src[j] == "\\":
                    raw.append(src[j])
                    j += 1
                raw.append(src[j])
                j += 1
            lits.append(y_unescape("".join(raw)))
            j += 1
            continue
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                break
        j += 1
    return lits


def main() -> int:
    out_path = sys.argv[1]
    parts = []
    for spec in sys.argv[2:]:
        path, func = spec.split(":")
        lits = extract(path, func)
        parts.append((func, lits))
    with open(out_path, "w") as f:
        f.write(
            "/* GENERATED by tools/gen_std_lines.py from the std modules'\n"
            " * embedded line arrays -- do not edit. These are the 1:1 C twins of\n"
            " * rt_lines()/prelude_lines()/exec_lines()/prelude_names()/exec_names().\n"
            " * The port gate (cmp against refs/ycc.ref) verifies the content. */\n"
            '#include "yv.h"\n\n'
        )
        for func, lits in parts:
            f.write("Yv *%s(void) {\n" % func)
            f.write("    Yv *out = yav(0);\n")
            for lit in lits:
                f.write('    out = ya_push(out, ys("%s"));\n' % c_escape(lit))
            f.write("    return out;\n}\n\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
